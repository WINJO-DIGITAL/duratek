#!/usr/bin/env node
/**
 * Builds supabase/seed.sql from the Kwik Floors Duratek collection.
 *
 *   node scripts/demo-seed/build-demo-seed.mjs
 *
 * Pulls finish names, sizes, specs, description copy and photography from the
 * public Shopify products.json, applies the hand curation in curation.json,
 * fetches a tiny blur placeholder per image, and writes SQL. Everything it
 * writes is marked is_demo. Kwik Floors prices are deliberately ignored; trade
 * prices in the seed are obvious placeholders.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const curation = JSON.parse(await readFile(path.join(here, "curation.json"), "utf8"));

// Placeholder trade prices: repeated digits so nobody mistakes them for real.
const DEMO_TIERS = [
  { name: "Demo tier A (placeholder prices)", pence: 2222 },
  { name: "Demo tier B (placeholder prices)", pence: 1111 },
];

const uuid = (seed) => {
  const h = createHash("sha1").update(`duratek-demo:${seed}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const decode = (s) =>
  s
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&#39;|&rsquo;|’/g, "’")
    .replace(/\s+/g, " ")
    .trim();
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function blurDataUrl(src) {
  const url = `${src}${src.includes("?") ? "&" : "?"}width=24`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`blur fetch ${res.status} for ${url}`);
  const type = res.headers.get("content-type") ?? "image/jpeg";
  const buf = Buffer.from(await res.arrayBuffer());
  return `data:${type};base64,${buf.toString("base64")}`;
}

function parseProduct(p) {
  const name = p.title
    .replace(/\s*Luxury Click Vinyl Flooring.*$/i, "")
    .trim();
  const thickness = Number(/(\d+(?:\.\d+)?)mm\s*$/i.exec(p.title)?.[1]);
  const v = p.variants[0]?.title ?? "";
  const size = /(\d+)\s*mm\s*x\s*(\d+)\s*mm/i.exec(v);
  const coverage = /([\d.]+)\s*m²/i.exec(v);
  if (!thickness || !size || !coverage) throw new Error(`Could not parse specs for ${p.handle}: "${p.title}" / "${v}"`);

  const body = p.body_html.replace(/<style[\s\S]*?<\/style>/g, "");
  const paras = [...body.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)].map((m) => decode(m[1]));
  const format = paras.find((t) => t.includes("·")) ?? "";
  const prose = paras.filter((t) => t.length > 80).slice(0, 2);
  if (prose.length < 2) throw new Error(`No description copy for ${p.handle}`);

  return {
    name,
    slug: slugify(name),
    description: prose.join("\n\n"),
    specs: {
      thickness_mm: thickness,
      plank_width_mm: Number(size[1]),
      plank_length_mm: Number(size[2]),
      pack_coverage_m2: Number(coverage[1]),
      edge: "Micro bevel",
      format: /extra-long/i.test(format) ? "Extra-long, wider plank" : "Straight plank",
      wear_layer_mm: 0.55,
      core: "Rigid SPC, waterproof",
      surface: "Duratek Scratch Shield",
      underlay: "Integrated",
      click_system: "Unilin click-lock, floating installation",
    },
  };
}

function altFor(name, kind, room) {
  if (kind === "room") return `${name} flooring in a ${room}`;
  if (kind === "closeup") return `Close-up of ${name} plank grain and micro bevel edge`;
  return `${name} plank swatch showing the wood-effect grain`;
}

async function main() {
  const res = await fetch(curation.source.collection);
  if (!res.ok) throw new Error(`products.json ${res.status}`);
  const { products } = await res.json();
  const byHandle = new Map(products.map((p) => [p.handle, p]));

  const out = [];
  out.push(
    "-- GENERATED by scripts/demo-seed/build-demo-seed.mjs. Do not edit by hand.",
    `-- Source: ${curation.source.collection}`,
    `-- Generated: ${new Date().toISOString()}`,
    "-- DEMO CONTENT for the client preview. Finishes, images and inspiration are",
    "-- marked is_demo. Trade prices are fake placeholders, NOT Kwik Floors prices.",
    "",
    "begin;",
    "",
  );

  // Price tiers
  for (const t of DEMO_TIERS) {
    out.push(`insert into public.price_tiers (id, name, is_demo) values (${q(uuid(`tier:${t.name}`))}, ${q(t.name)}, true);`);
  }
  out.push("");

  const missing = curation.finishes.filter((f) => !byHandle.has(f.handle)).map((f) => f.handle);
  if (missing.length) throw new Error(`Products missing from collection: ${missing.join(", ")}`);
  const uncurated = products.filter((p) => !curation.finishes.some((f) => f.handle === p.handle));
  if (uncurated.length) console.warn(`Not curated, skipped: ${uncurated.map((p) => p.handle).join(", ")}`);

  const imageMeta = new Map(); // `${handle}:${i}` -> {src,width,height,blur,alt}

  for (const [order, f] of curation.finishes.entries()) {
    const p = byHandle.get(f.handle);
    const d = parseProduct(p);
    // Curated copy replaces the retailer's boilerplate when present.
    if (f.description) d.description = f.description;
    const fid = uuid(`finish:${f.handle}`);
    out.push(
      `insert into public.finishes (id, name, slug, style, colour_family, description, specs, sort_order, published, is_demo) values (` +
        `${q(fid)}, ${q(d.name)}, ${q(d.slug)}, 'plank', ${q(f.colour_family)}, ${q(d.description)}, ${q(JSON.stringify(d.specs))}::jsonb, ${order * 10}, true, true);`,
    );
    for (const [sort, img] of f.images.entries()) {
      const im = p.images[img.i];
      if (!im) throw new Error(`${f.handle} has no image ${img.i}`);
      const blur = await blurDataUrl(im.src);
      const alt = altFor(d.name, img.kind, img.room);
      imageMeta.set(`${f.handle}:${img.i}`, { src: im.src, width: im.width, height: im.height, blur, alt, fid });
      out.push(
        `insert into public.finish_images (finish_id, url, kind, alt, width, height, blur_data_url, sort_order) values (` +
          `${q(fid)}, ${q(im.src)}, '${img.kind}', ${q(alt)}, ${im.width}, ${im.height}, ${q(blur)}, ${sort});`,
      );
    }
    for (const t of DEMO_TIERS) {
      out.push(
        `insert into public.prices (finish_id, tier_id, price_per_m2_pence) values (${q(fid)}, ${q(uuid(`tier:${t.name}`))}, ${t.pence});`,
      );
    }
    out.push("");
  }

  for (const [order, ins] of curation.inspiration.entries()) {
    const m = imageMeta.get(`${ins.handle}:${ins.i}`);
    if (!m) throw new Error(`Inspiration image ${ins.handle}:${ins.i} is not in the curated finish images`);
    out.push(
      `insert into public.inspiration (title, mood, image_path, alt, width, height, blur_data_url, finish_ids, sort_order, published, is_demo) values (` +
        `${q(ins.title)}, ${q(ins.mood)}, ${q(m.src)}, ${q(m.alt)}, ${m.width}, ${m.height}, ${q(m.blur)}, array[${q(m.fid)}]::uuid[], ${order * 10}, true, true);`,
    );
  }
  out.push("");

  out.push(
    "-- Kwik Floors is a real online retailer of Duratek (not demo data).",
    `insert into public.online_retailers (name, url, sort_order, published) values ('Kwik Floors', ${q(curation.source.retailer_url)}, 0, true);`,
    "",
    "-- No stockists are seeded: the client has not supplied a list yet.",
    "",
    "commit;",
    "",
  );

  await writeFile(path.join(root, "supabase/seed.sql"), out.join("\n"));
  console.log(`Wrote supabase/seed.sql: ${curation.finishes.length} finishes, ${imageMeta.size} images, ${curation.inspiration.length} inspiration items.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
