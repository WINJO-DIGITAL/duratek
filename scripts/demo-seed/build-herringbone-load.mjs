#!/usr/bin/env node
/**
 * Writes supabase/demo-herringbone.sql: an insert-only, repeatable load of the
 * herringbone finishes, for a database that already has the plank finishes
 * (for example production after the migrations). Works offline from the
 * trimmed feed in herringbone-feed.json and the hand curation in curation.json.
 *
 *   node scripts/demo-seed/build-herringbone-load.mjs
 *
 * Nothing is updated or deleted: a finish whose slug already exists is left
 * alone, and every other row is added only if missing. Marked is_demo. Prices
 * are the same fake placeholders as the rest of the demo seed.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parseProduct } from "./build-demo-seed.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const curation = JSON.parse(await readFile(path.join(here, "curation.json"), "utf8"));
const feed = JSON.parse(await readFile(path.join(here, "herringbone-feed.json"), "utf8"));

// Same ids and placeholders as build-demo-seed.mjs, so a later full regeneration matches.
const DEMO_RRP_PENCE = 3333;
const DEMO_TIERS = [
  { name: "Demo tier A (placeholder prices)", pence: 2222 },
  { name: "Demo tier B (placeholder prices)", pence: 1111 },
];
const uuid = (seed) => {
  const h = createHash("sha1").update(`duratek-demo:${seed}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const altFor = (name, kind, room) =>
  kind === "room"
    ? `${name} flooring in a ${room}`
    : kind === "closeup"
      ? `Close-up of ${name} plank grain and micro bevel edge`
      : `${name} plank swatch showing the wood-effect grain`;

const byHandle = new Map(feed.products.map((p) => [p.handle, p]));
const chosen = curation.finishes.filter((f) => f.style === "herringbone");
if (!chosen.length) throw new Error("No herringbone finishes in curation.json");

const out = [
  "-- GENERATED by scripts/demo-seed/build-herringbone-load.mjs. Do not edit by hand.",
  "-- Insert-only and repeatable: adds the herringbone demo finishes to a database that already",
  "-- has the plank finishes. Existing rows are never changed or deleted. Needs the migrations",
  "-- applied first (it calls public.backfill_foundation()). Demo content; fake placeholder prices.",
  "",
  "begin;",
  "",
  "-- Their own collection, so the backfill below does not file them under the plank collections.",
  "insert into public.collections (name, slug, sort_order, published, is_demo) values ('Herringbone', 'herringbone', 3, true, true) on conflict do nothing;",
  "",
];

const base = curation.finishes.length - chosen.length;
for (const [n, f] of chosen.entries()) {
  const p = byHandle.get(f.handle);
  if (!p) throw new Error(`${f.handle} is not in herringbone-feed.json`);
  const d = parseProduct(p, "herringbone");
  if (f.description) d.description = f.description;
  const fid = uuid(`finish:${f.handle}`);
  out.push(`-- ${d.name}`);
  out.push(
    `insert into public.finishes (id, name, slug, style, colour_family, description, specs, sort_order, published, is_demo) ` +
      `select ${q(fid)}, ${q(d.name)}, ${q(d.slug)}, 'herringbone', ${q(f.colour_family)}, ${q(d.description)}, ${q(JSON.stringify(d.specs))}::jsonb, ${(base + n) * 10}, true, true ` +
      `where not exists (select 1 from public.finishes where slug = ${q(d.slug)});`,
  );
  for (const [sort, img] of f.images.entries()) {
    const im = p.images[img.i];
    if (!im) throw new Error(`${f.handle} has no image ${img.i}`);
    out.push(
      `insert into public.finish_images (finish_id, url, kind, alt, width, height, blur_data_url, sort_order) ` +
        `select ${q(fid)}, ${q(im.src)}, '${img.kind}', ${q(altFor(d.name, img.kind, img.room))}, ${im.width}, ${im.height}, null, ${sort} ` +
        `where exists (select 1 from public.finishes where id = ${q(fid)}) ` +
        `and not exists (select 1 from public.finish_images where finish_id = ${q(fid)} and url = ${q(im.src)});`,
    );
  }
  for (const t of DEMO_TIERS) {
    out.push(
      `insert into public.prices (finish_id, tier_id, price_per_m2_pence) ` +
        `select ${q(fid)}, t.id, ${t.pence} from public.price_tiers t where t.name = ${q(t.name)} ` +
        `and exists (select 1 from public.finishes where id = ${q(fid)}) on conflict do nothing;`,
    );
  }
  out.push(`update public.finishes set rrp_per_m2_pence = ${DEMO_RRP_PENCE} where id = ${q(fid)} and rrp_per_m2_pence is null;`);
  out.push(
    `update public.finishes set collection_id = (select id from public.collections where slug = 'herringbone') where id = ${q(fid)} and collection_id is null;`,
    "",
  );
}

out.push(
  "-- Default variant and price-list rows for the new finishes (repeatable: skips what exists).",
  "select public.backfill_foundation();",
  "",
  "commit;",
  "",
);

await writeFile(path.join(root, "supabase/demo-herringbone.sql"), out.join("\n"));
console.log(`Wrote supabase/demo-herringbone.sql: ${chosen.length} herringbone finishes.`);
